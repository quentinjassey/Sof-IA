// =============================================================================
// SOF'IA — Results Importer Service
//
// Imports the complete N8N analysis payload into Supabase.
// This is the core of the architecture: after this import, N8N is no longer
// needed for the mission. All data lives in Supabase.
//
// Steps:
//   1. Insert ecritures (parsed FEC entries)
//   2. Insert rapprochements (document-to-entry matching)
//   3. Insert signals (all with human_decision = 'pending')
//   4. Insert/update completeness records
//   5. Store deliverable files in Supabase Storage + metadata in DB
//   6. Create traces for each imported signal (actor = 'sofia')
//   7. Create trace for analysis completion (actor = 'sofia')
//   8. Update mission status to 'analyzed'
//
// If any step fails, the mission status is set to 'analysis_failed'.
//
// IMPORTANT:
//   - All signals start with human_decision = 'pending'
//   - No signal can be auto-dismissed
//   - Every imported signal generates a trace entry
//   - Uses proper French labels (no forbidden vocabulary)
// =============================================================================

import { createServerSupabaseClient } from '@/lib/supabase/server'
import type { SupabaseClient } from '@supabase/supabase-js'
import type {
  EcritureInsert,
  RapprochementInsert,
  SignalInsert,
  CompletenessInsert,
  DeliverableInsert,
  TraceInsert,
  TraceAction,
} from '@/types/database'
import type {
  N8NAnalysisResults,
  N8NEcriture,
  N8NRapprochement,
  N8NSignal,
  N8NCompletenessEntry,
  N8NDeliverable,
  N8NTrace,
} from '@/types/n8n'

// -----------------------------------------------------------------------------
// Types
// -----------------------------------------------------------------------------

/** Summary returned after import completes */
export interface ImportSummary {
  ecritures_imported: number
  rapprochements_imported: number
  signals_imported: number
  completeness_imported: number
  deliverables_imported: number
  traces_imported: number
}

/** Import result (success or failure) */
export interface ImportResult {
  success: boolean
  summary?: ImportSummary
  error?: string
  step?: string
}

// -----------------------------------------------------------------------------
// ID Mapping helpers
// -----------------------------------------------------------------------------

/**
 * Maps N8N-generated IDs to Supabase-generated UUIDs.
 * N8N sends its own IDs for ecritures, rapprochements, signals, etc.
 * We need to map these to the UUIDs generated by Supabase on insert.
 */
type IdMap = Map<string, string>

// -----------------------------------------------------------------------------
// Main Import Function
// -----------------------------------------------------------------------------

/**
 * Imports the complete N8N analysis results into Supabase.
 *
 * This function is called by the analysis status polling API route
 * when N8N signals that analysis is complete.
 *
 * @param missionId - The UUID of the mission
 * @param licenseId - The UUID of the license (for data isolation)
 * @param results - The complete N8N analysis payload
 * @returns ImportResult with summary or error details
 */
export async function importAnalysisResults(
  missionId: string,
  licenseId: string,
  results: N8NAnalysisResults
): Promise<ImportResult> {
  const supabase = createServerSupabaseClient()

  // Track ID mappings from N8N IDs to Supabase IDs
  const ecritureIdMap: IdMap = new Map()
  const rapprochementIdMap: IdMap = new Map()

  const summary: ImportSummary = {
    ecritures_imported: 0,
    rapprochements_imported: 0,
    signals_imported: 0,
    completeness_imported: 0,
    deliverables_imported: 0,
    traces_imported: 0,
  }

  try {
    // =========================================================================
    // Step 1: Find the FEC document ID for linking ecritures
    // =========================================================================
    const { data: fecDoc } = await supabase
      .from('documents')
      .select('id')
      .eq('mission_id', missionId)
      .eq('type', 'fec')
      .limit(1)
      .single()

    const fecDocumentId = fecDoc?.id || null

    // =========================================================================
    // Step 2: Import ecritures (parsed FEC entries)
    // =========================================================================
    if (results.ecritures && results.ecritures.length > 0) {
      const ecritureRows = results.ecritures.map((e: N8NEcriture): EcritureInsert => ({
        mission_id: missionId,
        document_id: fecDocumentId,
        journal_code: e.journal_code,
        journal_lib: e.journal_lib,
        ecriture_num: e.ecriture_num,
        ecriture_date: e.ecriture_date,
        compte_num: e.compte_num,
        compte_lib: e.compte_lib,
        comp_aux_num: e.comp_aux_num,
        comp_aux_lib: e.comp_aux_lib,
        piece_ref: e.piece_ref,
        piece_date: e.piece_date,
        ecriture_lib: e.ecriture_lib,
        debit: e.debit || 0,
        credit: e.credit || 0,
        lettrage: e.lettrage,
        date_lettrage: e.date_lettrage,
        valid_date: e.valid_date,
      }))

      // Insert in batches of 100 to avoid payload limits
      const batchSize = 100
      for (let i = 0; i < ecritureRows.length; i += batchSize) {
        const batch = ecritureRows.slice(i, i + batchSize)
        const { data: insertedEcritures, error: ecritureError } = await supabase
          .from('ecritures')
          .insert(batch)
          .select('id')

        if (ecritureError) {
          console.error('Erreur import ecritures (batch):', ecritureError)
          await markMissionFailed(supabase, missionId, licenseId)
          return {
            success: false,
            error: `Erreur lors de l'import des ecritures comptables : ${ecritureError.message}`,
            step: 'ecritures',
          }
        }

        // Map N8N IDs to Supabase IDs
        if (insertedEcritures) {
          for (let j = 0; j < insertedEcritures.length; j++) {
            const n8nId = results.ecritures[i + j]?.id
            if (n8nId) {
              ecritureIdMap.set(n8nId, insertedEcritures[j].id)
            }
          }
          summary.ecritures_imported += insertedEcritures.length
        }
      }
    }

    // =========================================================================
    // Step 3: Import rapprochements (document-to-entry matching)
    // =========================================================================
    if (results.rapprochements && results.rapprochements.length > 0) {
      const rapprochementRows = results.rapprochements.map(
        (r: N8NRapprochement): RapprochementInsert => ({
          mission_id: missionId,
          ecriture_id: ecritureIdMap.get(r.ecriture_id) || r.ecriture_id,
          document_id: r.document_id || null,
          match_type: r.match_type,
          match_details: r.match_details,
          confidence: r.confidence,
          created_by: 'sofia',
        })
      )

      // Insert in batches
      const batchSize = 100
      for (let i = 0; i < rapprochementRows.length; i += batchSize) {
        const batch = rapprochementRows.slice(i, i + batchSize)
        const { data: insertedRapprochements, error: rapprochementError } = await supabase
          .from('rapprochements')
          .insert(batch)
          .select('id')

        if (rapprochementError) {
          console.error('Erreur import rapprochements (batch):', rapprochementError)
          await markMissionFailed(supabase, missionId, licenseId)
          return {
            success: false,
            error: `Erreur lors de l'import des rapprochements : ${rapprochementError.message}`,
            step: 'rapprochements',
          }
        }

        // Map N8N IDs to Supabase IDs
        if (insertedRapprochements) {
          for (let j = 0; j < insertedRapprochements.length; j++) {
            const n8nId = results.rapprochements[i + j]?.id
            if (n8nId) {
              rapprochementIdMap.set(n8nId, insertedRapprochements[j].id)
            }
          }
          summary.rapprochements_imported += insertedRapprochements.length
        }
      }
    }

    // =========================================================================
    // Step 4: Import signals (all with human_decision = 'pending')
    // =========================================================================
    if (results.signals && results.signals.length > 0) {
      const signalRows = results.signals.map((s: N8NSignal): SignalInsert => ({
        mission_id: missionId,
        document_id: s.document_id || null,
        ecriture_id: s.ecriture_id
          ? ecritureIdMap.get(s.ecriture_id) || s.ecriture_id
          : null,
        rapprochement_id: s.rapprochement_id
          ? rapprochementIdMap.get(s.rapprochement_id) || s.rapprochement_id
          : null,
        type: s.type,
        description: s.description,
        source_document: s.source_document,
        source_page: s.source_page,
        source_extract: s.source_extract,
        rule_triggered: s.rule_triggered,
        rule_description: s.rule_description,
        priority: s.priority,
        explicability: s.explicability,
        // CRITICAL: All signals start as 'pending' — human validation required
        human_decision: 'pending',
        human_comment: null,
        decided_at: null,
      }))

      const { data: insertedSignals, error: signalError } = await supabase
        .from('signals')
        .insert(signalRows)
        .select('id, rule_triggered, type, priority')

      if (signalError) {
        console.error('Erreur import signaux:', signalError)
        await markMissionFailed(supabase, missionId, licenseId)
        return {
          success: false,
          error: `Erreur lors de l'import des signaux documentaires : ${signalError.message}`,
          step: 'signals',
        }
      }

      summary.signals_imported = insertedSignals?.length || 0

      // Create a trace for each imported signal (actor = 'sofia')
      if (insertedSignals && insertedSignals.length > 0) {
        const signalTraces: TraceInsert[] = insertedSignals.map((s) => ({
          mission_id: missionId,
          license_id: licenseId,
          timestamp: results.completed_at || new Date().toISOString(),
          actor: 'sofia' as const,
          actor_name: "Sof'IA",
          action: 'signals_generated' as const,
          target_type: 'signal' as const,
          target_id: s.id,
          details: `Signal documentaire detecte : ${s.rule_triggered || s.type} (priorite ${s.priority})`,
        }))

        const { error: signalTraceError } = await supabase
          .from('traces')
          .insert(signalTraces)

        if (signalTraceError) {
          // Log but continue — signal import succeeded
          console.error('Erreur creation traces signaux:', signalTraceError)
        } else {
          summary.traces_imported += signalTraces.length
        }
      }
    }

    // =========================================================================
    // Step 5: Import/update completeness records
    // =========================================================================
    if (results.completeness && results.completeness.length > 0) {
      // Delete existing completeness records for this mission before inserting new ones
      await supabase
        .from('completeness')
        .delete()
        .eq('mission_id', missionId)

      const completenessRows = results.completeness.map(
        (c: N8NCompletenessEntry): CompletenessInsert => ({
          mission_id: missionId,
          doc_type: c.type,
          label: c.label,
          required: c.required,
          status: c.status,
          count: c.count || 0,
          note: c.note || null,
        })
      )

      const { error: completenessError } = await supabase
        .from('completeness')
        .insert(completenessRows)

      if (completenessError) {
        console.error('Erreur import completude:', completenessError)
        await markMissionFailed(supabase, missionId, licenseId)
        return {
          success: false,
          error: `Erreur lors de l'import de la completude documentaire : ${completenessError.message}`,
          step: 'completeness',
        }
      }

      summary.completeness_imported = completenessRows.length
    }

    // =========================================================================
    // Step 6: Import deliverables (files to Storage + metadata to DB)
    // =========================================================================
    if (results.deliverables && results.deliverables.length > 0) {
      for (const deliverable of results.deliverables) {
        try {
          const storagePath = await storeDeliverableFile(
            supabase,
            missionId,
            deliverable
          )

          const deliverableRow: DeliverableInsert = {
            mission_id: missionId,
            type: deliverable.type,
            format: deliverable.format,
            title: deliverable.title,
            generated_at: results.completed_at || new Date().toISOString(),
            content_json: deliverable.content_json || null,
            storage_path: storagePath,
          }

          const { error: deliverableError } = await supabase
            .from('deliverables')
            .insert(deliverableRow)

          if (deliverableError) {
            console.error('Erreur import livrable:', deliverableError)
            // Continue with other deliverables — don't fail the whole import
          } else {
            summary.deliverables_imported++
          }
        } catch (err) {
          console.error(`Erreur stockage livrable ${deliverable.type}:`, err)
          // Continue with other deliverables
        }
      }
    }

    // =========================================================================
    // Step 7: Import N8N traces (analysis process traces)
    // =========================================================================
    if (results.traces && results.traces.length > 0) {
      const n8nTraces: TraceInsert[] = results.traces.map((t: N8NTrace) => ({
        mission_id: missionId,
        license_id: licenseId,
        timestamp: t.timestamp,
        actor: t.actor || ('sofia' as const),
        actor_name: "Sof'IA",
        action: mapN8NAction(t.action),
        target_type: 'mission' as const,
        target_id: missionId,
        details: t.details,
      }))

      const { error: traceError } = await supabase
        .from('traces')
        .insert(n8nTraces)

      if (traceError) {
        console.error('Erreur import traces N8N:', traceError)
        // Non-critical — continue
      } else {
        summary.traces_imported += n8nTraces.length
      }
    }

    // =========================================================================
    // Step 8: Create analysis_completed trace
    // =========================================================================
    const { error: completionTraceError } = await supabase
      .from('traces')
      .insert({
        mission_id: missionId,
        license_id: licenseId,
        timestamp: new Date().toISOString(),
        actor: 'sofia' as const,
        actor_name: "Sof'IA",
        action: 'analysis_completed' as const,
        target_type: 'mission' as const,
        target_id: missionId,
        details: `Pre-analyse terminee. ${summary.ecritures_imported} ecritures importees, ${summary.rapprochements_imported} rapprochements, ${summary.signals_imported} signaux documentaires detectes, ${summary.deliverables_imported} livrables generes.`,
      })

    if (completionTraceError) {
      console.error('Erreur creation trace completion:', completionTraceError)
    } else {
      summary.traces_imported++
    }

    // =========================================================================
    // Step 9: Update mission status to 'analyzed'
    // =========================================================================
    const { error: missionUpdateError } = await supabase
      .from('missions')
      .update({
        status: 'analyzed',
        updated_at: new Date().toISOString(),
      })
      .eq('id', missionId)

    if (missionUpdateError) {
      console.error('Erreur mise a jour statut mission:', missionUpdateError)
      // The data is imported, so we still return success
      // The status will be corrected on next access
    }

    return {
      success: true,
      summary,
    }
  } catch (error) {
    console.error('Erreur inattendue lors de l\'import des resultats:', error)
    await markMissionFailed(supabase, missionId, licenseId)
    return {
      success: false,
      error: `Erreur inattendue : ${error instanceof Error ? error.message : 'Erreur inconnue'}`,
      step: 'unknown',
    }
  }
}

