/**
 * Marks a mission as failed when import encounters an error.
 */
async function markMissionFailed(
  supabase: SupabaseClient,
  missionId: string,
  licenseId: string
): Promise<void> {
  try {
    await supabase
      .from('missions')
      .update({
        status: 'analysis_failed',
        updated_at: new Date().toISOString(),
      })
      .eq('id', missionId)

    // Also create a trace for the failure
    await supabase
      .from('traces')
      .insert({
        mission_id: missionId,
        license_id: licenseId,
        timestamp: new Date().toISOString(),
        actor: 'sofia' as const,
        actor_name: "Sof'IA",
        action: 'analysis_failed' as const,
        target_type: 'mission' as const,
        target_id: missionId,
        details: "L'import des resultats de la pre-analyse a echoue.",
      })
  } catch (err) {
    console.error('Erreur lors du marquage de la mission en echec:', err)
  }
}

/**
 * Stores a deliverable file in Supabase Storage.
 * The file content comes as base64 from N8N.
 *
 * @returns The storage path of the uploaded file
 */
async function storeDeliverableFile(
  supabase: SupabaseClient,
  missionId: string,
  deliverable: N8NDeliverable
): Promise<string> {
  const fileName = `${deliverable.type}.${deliverable.format}`
  const storagePath = `${missionId}/${fileName}`

  if (!deliverable.file_base64) {
    // No file content — return path for metadata-only storage
    return storagePath
  }

  // Decode base64 content
  const binaryStr = atob(deliverable.file_base64)
  const bytes = new Uint8Array(binaryStr.length)
  for (let i = 0; i < binaryStr.length; i++) {
    bytes[i] = binaryStr.charCodeAt(i)
  }

  const contentType = deliverable.format === 'pdf'
    ? 'application/pdf'
    : 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'

  const { error: uploadError } = await supabase.storage
    .from('deliverables')
    .upload(storagePath, bytes, {
      contentType,
      upsert: true,
    })

  if (uploadError) {
    console.error(`Erreur upload livrable ${fileName}:`, uploadError)
    throw uploadError
  }

  return storagePath
}

/**
 * Maps N8N action strings to valid TraceAction values.
 * N8N may send action strings that don't exactly match our enum,
 * so we normalize them here.
 */
function mapN8NAction(action: string): TraceAction {
  const actionMap: Record<string, TraceAction> = {
    analysis_started: 'analysis_started',
    fec_parsed: 'fec_parsed',
    pdf_extracted: 'pdf_extracted',
    rapprochement_completed: 'rapprochement_completed',
    signals_generated: 'signals_generated',
    deliverables_generated: 'deliverables_generated',
    analysis_completed: 'analysis_completed',
    analysis_failed: 'analysis_failed',
  }

  // Default to 'analysis_completed' if action not found in map
  return actionMap[action] || ('analysis_completed' as TraceAction)
}
